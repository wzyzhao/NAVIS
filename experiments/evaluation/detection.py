"""Run YOLO on reconstructed frames and score it against source semantic ROIs.

The source reference is the ROI set generated by the same YOLOv8s processing
pipeline, not MOTChallenge human annotations.  The resulting precision,
recall, and F1 are therefore detector-consistency metrics for the cloud task.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from ultralytics import YOLO


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate cloud YOLO task on reconstructed NAVIS frames.")
    parser.add_argument("--frames", type=Path, required=True, help="Reconstructed PNG directory for one node.")
    parser.add_argument(
        "--source-root", type=Path, required=True, help="Source factorization directory with metadata.json files."
    )
    parser.add_argument(
        "--received-manifest",
        type=Path,
        required=True,
        help="Receiver manifest JSONL; complete ROI entries define the evaluation reference.",
    )
    parser.add_argument(
        "--weights",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "src/common/models/yolov8s.pt",
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--confidence", type=float, default=0.25)
    parser.add_argument("--iou-threshold", type=float, default=0.5)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--device", default="", help="Ultralytics device, empty lets it choose.")
    return parser.parse_args()


def iou_xyxy(left: list[float], right: list[float]) -> float:
    x1, y1 = max(left[0], right[0]), max(left[1], right[1])
    x2, y2 = min(left[2], right[2]), min(left[3], right[3])
    intersection = max(0.0, x2 - x1) * max(0.0, y2 - y1)
    left_area = max(0.0, left[2] - left[0]) * max(0.0, left[3] - left[1])
    right_area = max(0.0, right[2] - right[0]) * max(0.0, right[3] - right[1])
    union = left_area + right_area - intersection
    return intersection / union if union else 0.0


def received_roi_indices(path: Path) -> dict[int, set[int]]:
    selected: dict[int, set[int]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        item = json.loads(line)
        if item.get("layer") != "roi_patch" or not item.get("ack_confirmed") or not item.get("ack_complete"):
            continue
        frame_idx, roi_idx = item.get("frame_idx"), item.get("roi_idx")
        if isinstance(frame_idx, int) and isinstance(roi_idx, int):
            selected.setdefault(frame_idx, set()).add(roi_idx)
    return selected


def source_targets(source_root: Path, frame_idx: int, received_indices: set[int]) -> list[dict]:
    path = source_root / f"{frame_idx:06d}" / "metadata.json"
    if not path.exists():
        return []
    raw = json.loads(path.read_text(encoding="utf-8"))
    targets = []
    for roi_idx, item in enumerate(raw.get("selected_rois", [])):
        if roi_idx not in received_indices:
            continue
        bbox = item.get("bbox")
        if not bbox or len(bbox) != 4:
            continue
        targets.append({"box": [float(v) for v in bbox], "class_id": int(item.get("class_id", -1))})
    return targets


def intersects_any_roi(prediction: dict, targets: list[dict]) -> bool:
    box = prediction["box"]
    center_x, center_y = (box[0] + box[2]) / 2.0, (box[1] + box[3]) / 2.0
    return any(
        target["box"][0] <= center_x <= target["box"][2] and target["box"][1] <= center_y <= target["box"][3]
        for target in targets
    )


def match(targets: list[dict], predictions: list[dict], threshold: float) -> tuple[int, int, int]:
    candidates = []
    for ti, target in enumerate(targets):
        for pi, prediction in enumerate(predictions):
            if target["class_id"] != prediction["class_id"]:
                continue
            overlap = iou_xyxy(target["box"], prediction["box"])
            if overlap >= threshold:
                candidates.append((overlap, ti, pi))
    candidates.sort(reverse=True)
    target_used, prediction_used = set(), set()
    true_positive = 0
    for _, ti, pi in candidates:
        if ti in target_used or pi in prediction_used:
            continue
        target_used.add(ti)
        prediction_used.add(pi)
        true_positive += 1
    return true_positive, len(predictions) - true_positive, len(targets) - true_positive


def main() -> None:
    args = parse_args()
    if not args.frames.is_dir() or not args.source_root.is_dir() or not args.received_manifest.is_file():
        raise ValueError("--frames, --source-root, and --received-manifest must exist")
    images = sorted(args.frames.glob("*.png"))
    if not images:
        raise ValueError("No reconstructed PNG frames found")
    model = YOLO(str(args.weights))
    received_indices = received_roi_indices(args.received_manifest)
    tp = fp = fn = reference_count = prediction_count = 0
    per_frame = []
    inference_args = {"conf": args.confidence, "imgsz": args.imgsz, "verbose": False}
    if args.device:
        inference_args["device"] = args.device
    for start in range(0, len(images), max(1, args.batch)):
        image_batch = images[start : start + max(1, args.batch)]
        results = model([str(image) for image in image_batch], batch=len(image_batch), **inference_args)
        for image, result in zip(image_batch, results):
            frame_idx = int(image.stem)
            targets = source_targets(args.source_root, frame_idx, received_indices.get(frame_idx, set()))
            predictions = []
            for box in result.boxes:
                predictions.append(
                    {
                        "box": [float(v) for v in box.xyxy[0].tolist()],
                        "class_id": int(box.cls[0].item()),
                        "confidence": float(box.conf[0].item()),
                    }
                )
            predictions = [prediction for prediction in predictions if intersects_any_roi(prediction, targets)]
            frame_tp, frame_fp, frame_fn = match(targets, predictions, args.iou_threshold)
            tp += frame_tp
            fp += frame_fp
            fn += frame_fn
            reference_count += len(targets)
            prediction_count += len(predictions)
            per_frame.append({"frame_idx": frame_idx, "tp": frame_tp, "fp": frame_fp, "fn": frame_fn})
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    output = {
        "task": "yolov8s_detection_on_reconstructed_frames",
        "reference": "complete ROI entries in the receiver manifest, localized with the source semantic ROI metadata; not MOTChallenge human ground truth",
        "metric_definition": "ROI-local, class-consistent greedy IoU matching at the configured threshold",
        "settings": {
            "weights": str(args.weights),
            "confidence": args.confidence,
            "iou_threshold": args.iou_threshold,
            "imgsz": args.imgsz,
            "batch": args.batch,
            "device": args.device or "auto",
            "received_manifest": str(args.received_manifest),
        },
        "frame_count": len(images),
        "reference_instances": reference_count,
        "predicted_instances": prediction_count,
        "true_positive": tp,
        "false_positive": fp,
        "false_negative": fn,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "per_frame": per_frame,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(json.dumps({key: output[key] for key in ("frame_count", "precision", "recall", "f1")}, indent=2))


if __name__ == "__main__":
    main()
